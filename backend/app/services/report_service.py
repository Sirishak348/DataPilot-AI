import os
import uuid
from datetime import datetime
from typing import Dict, Any, List, Optional

from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak, KeepTogether, HRFlowable
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.pdfgen import canvas

from app.config import settings

class NumberedCanvas(canvas.Canvas):
    """Adds running header and footer with page numbers."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))
        
        # Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(54, 750, "DataPilot AI — Automated Analytics Report")
            self.setStrokeColor(colors.HexColor("#cbd5e1"))
            self.setLineWidth(0.5)
            self.line(54, 742, 558, 742)

        # Footer
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(558, 36, page_str)
        self.drawString(54, 36, "Confidential & Generated by DataPilot AI Platform")
        self.setStrokeColor(colors.HexColor("#cbd5e1"))
        self.setLineWidth(0.5)
        self.line(54, 48, 558, 48)
        self.restoreState()

def generate_pdf_report(
    dataset_name: str,
    profile_data: Dict[str, Any],
    cleaning_stats: Optional[Dict[str, Any]] = None,
    model_runs: Optional[List[Dict[str, Any]]] = None
) -> str:
    """
    Generates a polished PDF report using ReportLab and returns the file path.
    """
    report_id = str(uuid.uuid4())
    filename = f"report_{report_id}.pdf"
    output_path = os.path.join(settings.STORAGE_DIR, "reports", filename)

    doc = SimpleDocTemplate(
        output_path,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54
    )

    styles = getSampleStyleSheet()
    
    # Custom styles
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=22,
        leading=26,
        textColor=colors.HexColor("#0f172a")
    )
    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#64748b")
    )
    h1_style = ParagraphStyle(
        'SectionH1',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=14,
        leading=18,
        textColor=colors.HexColor("#1e293b"),
        spaceBefore=14,
        spaceAfter=6
    )
    body_style = ParagraphStyle(
        'BodyDark',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#334155")
    )
    bold_style = ParagraphStyle(
        'BodyDarkBold',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#0f172a")
    )
    table_cell_style = ParagraphStyle(
        'TableCell',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#1e293b")
    )
    table_header_style = ParagraphStyle(
        'TableHeader',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#ffffff")
    )

    story = []

    # Title & Branding Banner
    story.append(Paragraph("DataPilot AI", ParagraphStyle('Brand', fontName='Helvetica-Bold', fontSize=12, textColor=colors.HexColor("#4f46e5"))))
    story.append(Spacer(1, 4))
    story.append(Paragraph(f"Executive Analytics Report: {dataset_name}", title_style))
    story.append(Paragraph(f"Generated on {datetime.utcnow().strftime('%B %d, %Y at %H:%M UTC')} | Automated Data Intelligence", subtitle_style))
    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#4f46e5"), spaceBefore=0, spaceAfter=14))

    # KPI Summary Cards (Table)
    quality = profile_data.get("quality", {})
    score = quality.get("overall_score", 0)
    grade = quality.get("grade", "N/A")

    kpi_data = [
        [
            Paragraph("<b>Total Rows</b>", table_cell_style),
            Paragraph("<b>Total Columns</b>", table_cell_style),
            Paragraph("<b>Data Quality Score</b>", table_cell_style),
            Paragraph("<b>Missing Cells</b>", table_cell_style),
            Paragraph("<b>Duplicate Rows</b>", table_cell_style),
        ],
        [
            Paragraph(f"<font size=12><b>{profile_data.get('row_count', 0):,}</b></font>", table_cell_style),
            Paragraph(f"<font size=12><b>{profile_data.get('column_count', 0)}</b></font>", table_cell_style),
            Paragraph(f"<font size=12 color='#0d9488'><b>{score}/100 ({grade})</b></font>", table_cell_style),
            Paragraph(f"<font size=12><b>{profile_data.get('missing_cells_percentage', 0)}%</b></font>", table_cell_style),
            Paragraph(f"<font size=12><b>{profile_data.get('duplicate_rows_percentage', 0)}%</b></font>", table_cell_style),
        ]
    ]

    kpi_table = Table(kpi_data, colWidths=[100, 100, 120, 94, 90])
    kpi_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#e2e8f0")),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
    ]))
    story.append(kpi_table)
    story.append(Spacer(1, 14))

    # Section 1: Data Quality Audit
    story.append(Paragraph("1. Data Quality & Health Audit", h1_style))
    notes = quality.get("breakdown_notes", [])
    if notes:
        for note in notes:
            story.append(Paragraph(f"• {note}", body_style))
    else:
        story.append(Paragraph("• No significant anomalies or schema defects identified.", body_style))
    story.append(Spacer(1, 10))

    # Section 2: Column Overview Table
    story.append(Paragraph("2. Schema & Attribute Profiling", h1_style))
    cols = profile_data.get("columns", [])
    
    col_table_data = [[
        Paragraph("<b>Column Name</b>", table_header_style),
        Paragraph("<b>Type</b>", table_header_style),
        Paragraph("<b>Nulls (%)</b>", table_header_style),
        Paragraph("<b>Unique</b>", table_header_style),
        Paragraph("<b>Outliers (IQR)</b>", table_header_style)
    ]]

    for c in cols[:30]:
        stats = c.get("stats")
        outliers_str = f"{stats.get('outlier_count', 0)} ({stats.get('outlier_percentage', 0)}%)" if stats else "N/A"
        col_table_data.append([
            Paragraph(c.get("name", ""), table_cell_style),
            Paragraph(c.get("inferred_type", ""), table_cell_style),
            Paragraph(f"{c.get('missing_count', 0)} ({c.get('missing_percentage', 0)}%)", table_cell_style),
            Paragraph(str(c.get("unique_count", 0)), table_cell_style),
            Paragraph(outliers_str, table_cell_style)
        ])

    col_table = Table(col_table_data, colWidths=[150, 80, 100, 74, 100])
    col_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#1e293b")),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
        ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#cbd5e1")),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
    ]))
    story.append(col_table)
    story.append(Spacer(1, 14))

    # Section 3: Descriptive Statistics for Numeric Columns
    numeric_cols = [c for c in cols if c.get("inferred_type") == "numeric" and c.get("stats")]
    if numeric_cols:
        story.append(Paragraph("3. Numeric Summary Statistics", h1_style))
        stats_table_data = [[
            Paragraph("<b>Feature</b>", table_header_style),
            Paragraph("<b>Mean</b>", table_header_style),
            Paragraph("<b>Std Dev</b>", table_header_style),
            Paragraph("<b>Min</b>", table_header_style),
            Paragraph("<b>Median</b>", table_header_style),
            Paragraph("<b>Max</b>", table_header_style),
            Paragraph("<b>Skewness</b>", table_header_style)
        ]]

        for nc in numeric_cols[:15]:
            st = nc["stats"]
            stats_table_data.append([
                Paragraph(nc["name"], table_cell_style),
                Paragraph(str(st.get("mean")), table_cell_style),
                Paragraph(str(st.get("std")), table_cell_style),
                Paragraph(str(st.get("min")), table_cell_style),
                Paragraph(str(st.get("median")), table_cell_style),
                Paragraph(str(st.get("max")), table_cell_style),
                Paragraph(str(st.get("skewness")), table_cell_style)
            ])

        stats_table = Table(stats_table_data, colWidths=[120, 64, 64, 64, 64, 64, 64])
        stats_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#334155")),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#cbd5e1")),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(stats_table)
        story.append(Spacer(1, 14))

    # Section 4: Data Cleaning Log (if any)
    if cleaning_stats and cleaning_stats.get("applied_operations"):
        story.append(Paragraph("4. Data Cleaning Audit Trail", h1_style))
        ops = cleaning_stats.get("applied_operations", [])
        for i, op in enumerate(ops, 1):
            msg = op.get("message", str(op))
            story.append(Paragraph(f"<b>Step {i}:</b> {msg}", body_style))
        story.append(Spacer(1, 14))

    # Section 5: Machine Learning Evaluation (if any)
    if model_runs:
        story.append(Paragraph("5. Machine Learning Models & Evaluation", h1_style))
        for idx, mr in enumerate(model_runs, 1):
            mname = mr.get("model_name")
            task = mr.get("task_type")
            target = mr.get("target_column") or "N/A"
            metrics = mr.get("metrics", {})

            story.append(Paragraph(f"<b>Experiment {idx}: {mname} ({task.capitalize()})</b> — Target: <code>{target}</code>", bold_style))
            
            # Format metrics string
            m_parts = []
            for k, v in metrics.items():
                if isinstance(v, (int, float)):
                    m_parts.append(f"<b>{k}:</b> {v}")
            story.append(Paragraph(" | ".join(m_parts), body_style))
            story.append(Spacer(1, 6))

    # Build document
    doc.build(story, canvasmaker=NumberedCanvas)
    return output_path
